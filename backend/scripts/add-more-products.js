async function run() {
  try {
    await connectDB();
    console.log('[add-products] Connected to MongoDB Atlas');

    let addedCount = 0;
    let updatedCount = 0;

    for (const item of newProducts) {
      const existing = await Product.findOne({ name: item.name });
      if (existing) {
        Object.assign(existing, item);
        await existing.save();
        updatedCount++;
      } else {
        await Product.create(item);
        addedCount++;
      }
    }

    const totalCount = await Product.countDocuments();
    const categories = await Product.distinct('category');
    console.log(`[add-products] Done! Added: ${addedCount}, Updated: ${updatedCount}`);
    console.log(`[add-products] Total products in database: ${totalCount}`);
    console.log(`[add-products] Available categories:`, categories);

    await mongoose.disconnect();
    process.exit(0);
  } catch (err) {
    console.error('[add-products] Error:', err);
    process.exit(1);
  }
}

run();
